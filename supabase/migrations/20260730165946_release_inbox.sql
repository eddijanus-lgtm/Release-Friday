  id uuid primary key default gen_random_uuid(),
  run_id uuid not null references public.release_import_runs(id) on delete cascade,
  artist text not null check (char_length(btrim(artist)) between 1 and 200),
  title text not null check (char_length(btrim(title)) between 1 and 240),
  release_date date not null,
  country text not null check (country in ('DE', 'US')),
  kind text not null check (kind in ('album', 'ep', 'single', 'mixtape')),
  track_count smallint null check (track_count is null or track_count between 1 and 999),
  description text null check (description is null or char_length(description) <= 5000),
  genres text[] not null default '{}',
  spotify_url text null,
  spotify_pre_save_url text null,
  apple_music_url text null,
  youtube_url text null,
  source_url text null,
  cover_url text null,
  storage_path text null,
  cover_kind text not null default 'missing'
    check (cover_kind in ('official', 'artist_fallback', 'missing')),
  primary_source text not null,
  sources jsonb not null default '[]'::jsonb check (jsonb_typeof(sources) = 'array'),
  confidence text not null default 'likely'
    check (confidence in ('uncertain', 'likely', 'confirmed')),
  warning_codes text[] not null default '{}',
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected', 'duplicate')),
