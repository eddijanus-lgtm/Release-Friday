create or replace function public.rollback_release_import(p_run_id uuid)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_change public.release_import_changes%rowtype;
  v_current public.releases%rowtype;
  v_restored integer := 0;
  v_skipped integer := 0;
  v_failed integer := 0;
begin
  if not exists (
    select 1
    from public.release_admins
    where user_id = (select auth.uid())
  ) then
    raise exception 'release admin access required';
  end if;

  perform 1
  from public.release_import_runs
  where id = p_run_id
  for update;

  if not found then
    raise exception 'release import run not found';
  end if;

  for v_change in
    select *
    from public.release_import_changes
    where run_id = p_run_id
      and rollback_status = 'pending'
    order by id desc
    for update
  loop
    begin
      select *
      into v_current
      from public.releases
      where identity_key = v_change.release_identity_key
      limit 1
      for update;

      if not found then
        update public.release_import_changes
        set
          rollback_status = 'skipped',
          rollback_message = 'Release no longer exists',
          rolled_back_at = now()
        where id = v_change.id;
        v_skipped := v_skipped + 1;
        continue;
      end if;

      if v_current.updated_at <> (v_change.after_snapshot ->> 'updated_at')::timestamptz then
        update public.release_import_changes
        set
          rollback_status = 'skipped',
          rollback_message = 'Release was edited after this import',
          rolled_back_at = now()
        where id = v_change.id;
        v_skipped := v_skipped + 1;
        continue;
      end if;

      if v_change.action = 'inserted' then
        delete from public.releases
        where id = v_current.id;
      else
        update public.releases
        set
          cover_url = v_change.before_snapshot ->> 'cover_url',
          storage_path = v_change.before_snapshot ->> 'storage_path',
          spotify_url = v_change.before_snapshot ->> 'spotify_url',
          spotify_pre_save_url = v_change.before_snapshot ->> 'spotify_pre_save_url',
          apple_music_url = v_change.before_snapshot ->> 'apple_music_url',
          youtube_url = v_change.before_snapshot ->> 'youtube_url',
          source_url = v_change.before_snapshot ->> 'source_url',
          description = v_change.before_snapshot ->> 'description',
          track_count = nullif(v_change.before_snapshot ->> 'track_count', '')::smallint,
          genres = coalesce(
            array(
              select jsonb_array_elements_text(v_change.before_snapshot -> 'genres')
            ),
            '{}'::text[]
          ),
          status = v_change.before_snapshot ->> 'status'
        where id = v_current.id;
      end if;

      update public.release_candidates
      set status = 'pending', matched_release_id = null
      where id = v_change.candidate_id;

      update public.release_import_changes
      set
        rollback_status = 'restored',
        rollback_message = null,
        rolled_back_at = now()
      where id = v_change.id;

      v_restored := v_restored + 1;
    exception
      when others then
        update public.release_import_changes
        set
          rollback_status = 'failed',
          rollback_message = left(sqlerrm, 500),
          rolled_back_at = now()
        where id = v_change.id;
        v_failed := v_failed + 1;
    end;
  end loop;

  update public.release_import_runs
  set
    status = case when v_failed = 0 and v_skipped = 0 then 'rolled_back' else 'review' end,
    completed_at = null
  where id = p_run_id;

  return jsonb_build_object(
    'restored', v_restored,
    'skipped', v_skipped,
    'failed', v_failed
  );
end;
$$;

revoke all on function public.rollback_release_import(uuid) from public, anon;
grant execute on function public.rollback_release_import(uuid) to authenticated;

