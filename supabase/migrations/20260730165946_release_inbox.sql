create or replace function private.release_identity_key(
  p_release_date date,
  p_artist text,
  p_title text
)
returns text
language sql
immutable
set search_path = ''
as $$
  select to_char(p_release_date, 'YYYY-MM-DD')
    || '|'
    || regexp_replace(
      translate(
        replace(
          regexp_replace(lower(btrim(coalesce(p_artist, ''))), '\s+(feat\.?|ft\.?|featuring|with|x|&|\+)\s+', '&', 'gi'),
          'ß',
          'ss'
        ),
        'äöüáàâãåéèêëíìîïóòôõúùûçñýÿ',
        'aouaaaaaeeeeiiiioooouuucnyy'
      ),
      '[^a-z0-9]+',
      '',
      'g'
    )
    || '|'
    || regexp_replace(
      translate(
        replace(lower(btrim(coalesce(p_title, ''))), 'ß', 'ss'),
        'äöüáàâãåéèêëíìîïóòôõúùûçñýÿ',
        'aouaaaaaeeeeiiiioooouuucnyy'
      ),
      '[^a-z0-9]+',
      '',
      'g'
    );
$$;

