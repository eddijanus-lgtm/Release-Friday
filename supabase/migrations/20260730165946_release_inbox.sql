create or replace function public.ingest_release_candidates(
  p_run_id uuid,
  p_candidates jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_processed integer := 0;
  v_pending integer := 0;
begin
  if jsonb_typeof(p_candidates) <> 'array' then
    raise exception 'candidates must be an array';
  end if;

  if jsonb_array_length(p_candidates) = 0 or jsonb_array_length(p_candidates) > 300 then
    raise exception 'candidates must contain between 1 and 300 items';
  end if;

  if not exists (
    select 1
    from public.release_import_runs
    where id = p_run_id
  ) then
    raise exception 'release import run not found';
  end if;

  with incoming_raw as (
    select source.ordinality, candidate.*
    from jsonb_array_elements(p_candidates) with ordinality as source(value, ordinality)
    cross join lateral jsonb_to_record(source.value) as candidate (
      artist text,
      title text,
      release_date date,
      country text,
      kind text,
      track_count smallint,
      description text,
      genres text[],
      spotify_url text,
      spotify_pre_save_url text,
      apple_music_url text,
      youtube_url text,
      source_url text,
      cover_url text,
      storage_path text,
      cover_kind text,
      primary_source text,
      sources jsonb,
      confidence text,
      warning_codes text[]
    )
  ),
  incoming as (
    select distinct on (private.release_identity_key(release_date, artist, title)) *
    from incoming_raw
    order by private.release_identity_key(release_date, artist, title), ordinality desc
  ),
  upserted as (
    insert into public.release_candidates (
      run_id,
      artist,
      title,
      release_date,
      country,
      kind,
      track_count,
      description,
      genres,
      spotify_url,
      spotify_pre_save_url,
      apple_music_url,
      youtube_url,
      source_url,
      cover_url,
      storage_path,
      cover_kind,
      primary_source,
      sources,
      confidence,
      warning_codes
    )
    select
      p_run_id,
      artist,
      title,
      release_date,
      country,
      kind,
      track_count,
      description,
      coalesce(genres, '{}'::text[]),
      spotify_url,
      spotify_pre_save_url,
      apple_music_url,
      youtube_url,
      source_url,
      cover_url,
      storage_path,
      coalesce(cover_kind, 'missing'),
      primary_source,
      coalesce(sources, '[]'::jsonb),
      coalesce(confidence, 'likely'),
      coalesce(warning_codes, '{}'::text[])
    from incoming
    on conflict (run_id, identity_key)
    do update set
      kind = excluded.kind,
      track_count = coalesce(excluded.track_count, release_candidates.track_count),
      description = coalesce(nullif(excluded.description, ''), release_candidates.description),
      genres = case
        when coalesce(array_length(excluded.genres, 1), 0) > 0 then excluded.genres
        else release_candidates.genres
      end,
      spotify_url = coalesce(nullif(excluded.spotify_url, ''), release_candidates.spotify_url),
      spotify_pre_save_url = coalesce(nullif(excluded.spotify_pre_save_url, ''), release_candidates.spotify_pre_save_url),
      apple_music_url = coalesce(nullif(excluded.apple_music_url, ''), release_candidates.apple_music_url),
      youtube_url = coalesce(nullif(excluded.youtube_url, ''), release_candidates.youtube_url),
      source_url = coalesce(nullif(excluded.source_url, ''), release_candidates.source_url),
      cover_url = coalesce(nullif(excluded.cover_url, ''), release_candidates.cover_url),
      storage_path = coalesce(nullif(excluded.storage_path, ''), release_candidates.storage_path),
      cover_kind = case
        when excluded.storage_path is not null then excluded.cover_kind
        else release_candidates.cover_kind
      end,
      primary_source = release_candidates.primary_source,
      sources = (
        select coalesce(jsonb_agg(source_item), '[]'::jsonb)
        from (
          select distinct source_item
          from jsonb_array_elements(
            coalesce(release_candidates.sources, '[]'::jsonb)
            || coalesce(excluded.sources, '[]'::jsonb)
          ) as source_item
        ) as merged_sources
      ),
      confidence = case
        when release_candidates.confidence = 'confirmed' or excluded.confidence = 'confirmed' then 'confirmed'
        when release_candidates.confidence = 'likely' or excluded.confidence = 'likely' then 'likely'
        else 'uncertain'
      end,
      warning_codes = array(
        select distinct warning
        from unnest(release_candidates.warning_codes || excluded.warning_codes) as warning
        where warning <> 'missing_stored_cover'
          or coalesce(excluded.storage_path, release_candidates.storage_path) is null
      )
    where release_candidates.status = 'pending'
    returning id
  )
  select count(*)::integer into v_processed from upserted;

  select count(*)::integer
  into v_pending
  from public.release_candidates
  where run_id = p_run_id
    and status = 'pending';

  update public.release_import_runs
  set
    status = 'review',
    completed_at = null,
    stats = jsonb_build_object(
      'pending', v_pending,
      'total', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id
      )
    )
  where id = p_run_id;

  return jsonb_build_object(
    'processed', v_processed,
    'pending', v_pending
  );
end;
$$;

revoke all on function public.ingest_release_candidates(uuid, jsonb) from public, anon, authenticated;
grant execute on function public.ingest_release_candidates(uuid, jsonb) to service_role;

create or replace function public.accept_release_candidates(
  p_run_id uuid,
  p_candidate_ids uuid[],
  p_status text default 'published'
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_candidate public.release_candidates%rowtype;
  v_existing public.releases%rowtype;
  v_after public.releases%rowtype;
  v_inserted integer := 0;
  v_updated integer := 0;
  v_skipped integer := 0;
  v_pending integer := 0;
begin
  if p_status not in ('draft', 'published') then
    raise exception 'status must be draft or published';
  end if;

  if coalesce(array_length(p_candidate_ids, 1), 0) = 0 then
    raise exception 'at least one candidate is required';
  end if;

  if not exists (
    select 1
    from public.release_admins
    where user_id = (select auth.uid())
  ) then
    raise exception 'release admin access required';
  end if;

  perform 1
  from public.release_import_runs
  where id = p_run_id
  for update;

  if not found then
    raise exception 'release import run not found';
  end if;

  update public.release_import_runs
  set status = 'processing', completed_at = null
  where id = p_run_id;

  for v_candidate in
    select *
    from public.release_candidates
    where run_id = p_run_id
      and id = any(p_candidate_ids)
      and status = 'pending'
    order by created_at, id
    for update
  loop
    select *
    into v_existing
    from public.releases
    where identity_key = v_candidate.identity_key
    limit 1
    for update;

    if found then
      update public.releases as release
      set
        cover_url = coalesce(nullif(release.cover_url, ''), v_candidate.cover_url),
        storage_path = coalesce(nullif(release.storage_path, ''), v_candidate.storage_path),
        spotify_url = coalesce(nullif(release.spotify_url, ''), v_candidate.spotify_url),
        spotify_pre_save_url = coalesce(nullif(release.spotify_pre_save_url, ''), v_candidate.spotify_pre_save_url),
        apple_music_url = coalesce(nullif(release.apple_music_url, ''), v_candidate.apple_music_url),
        youtube_url = coalesce(nullif(release.youtube_url, ''), v_candidate.youtube_url),
        source_url = coalesce(nullif(release.source_url, ''), v_candidate.source_url),
        description = coalesce(nullif(release.description, ''), v_candidate.description),
        track_count = coalesce(release.track_count, v_candidate.track_count),
        genres = case
          when coalesce(array_length(release.genres, 1), 0) = 0 then v_candidate.genres
          else release.genres
        end,
        status = p_status
      where release.id = v_existing.id
      returning * into v_after;

      insert into public.release_import_changes (
        run_id,
        candidate_id,
        release_id,
        release_identity_key,
        action,
        before_snapshot,
        after_snapshot
      )
      values (
        p_run_id,
        v_candidate.id,
        v_after.id,
        v_candidate.identity_key,
        'updated',
        to_jsonb(v_existing),
        to_jsonb(v_after)
      );

      update public.release_candidates
      set status = 'duplicate', matched_release_id = v_after.id
      where id = v_candidate.id;

      v_updated := v_updated + 1;
      continue;
    end if;

    if p_status = 'published'
      and (v_candidate.cover_url is null or v_candidate.storage_path is null)
    then
      update public.release_candidates
      set warning_codes = array(
        select distinct code
        from unnest(warning_codes || array['missing_stored_cover']::text[]) as code
      )
      where id = v_candidate.id;
      v_skipped := v_skipped + 1;
      continue;
    end if;

    insert into public.releases (
      artist,
      title,
      release_date,
      country,
      kind,
      track_count,
      description,
      genres,
      spotify_url,
      spotify_pre_save_url,
      apple_music_url,
      youtube_url,
      source_url,
      cover_url,
      storage_path,
      source,
      status,
      created_by
    )
    values (
      v_candidate.artist,
      v_candidate.title,
      v_candidate.release_date,
      v_candidate.country,
      v_candidate.kind,
      v_candidate.track_count,
      v_candidate.description,
      v_candidate.genres,
      v_candidate.spotify_url,
      v_candidate.spotify_pre_save_url,
      v_candidate.apple_music_url,
      v_candidate.youtube_url,
      v_candidate.source_url,
      v_candidate.cover_url,
      v_candidate.storage_path,
      'Release Inbox · ' || v_candidate.primary_source,
      p_status,
      (select auth.uid())
    )
    returning * into v_after;

    insert into public.release_import_changes (
      run_id,
      candidate_id,
      release_id,
      release_identity_key,
      action,
      before_snapshot,
      after_snapshot
    )
    values (
      p_run_id,
      v_candidate.id,
      v_after.id,
      v_candidate.identity_key,
      'inserted',
      null,
      to_jsonb(v_after)
    );

    update public.release_candidates
    set status = 'accepted', matched_release_id = v_after.id
    where id = v_candidate.id;

    v_inserted := v_inserted + 1;
  end loop;

  select count(*)::integer
  into v_pending
  from public.release_candidates
  where run_id = p_run_id
    and status = 'pending';

  update public.release_import_runs
  set
    status = case when v_pending = 0 then 'completed' else 'review' end,
    completed_at = case when v_pending = 0 then now() else null end,
    stats = jsonb_build_object(
      'pending', v_pending,
      'accepted', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'accepted'
      ),
      'duplicates', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'duplicate'
      ),
      'rejected', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'rejected'
      )
    )
  where id = p_run_id;

  return jsonb_build_object(
    'inserted', v_inserted,
    'updated', v_updated,
    'skipped', v_skipped,
    'pending', v_pending
  );
end;
$$;

