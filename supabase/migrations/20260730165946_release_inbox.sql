  update public.release_import_runs
  set
    status = case when v_pending = 0 then 'completed' else 'review' end,
    completed_at = case when v_pending = 0 then now() else null end,
    stats = jsonb_build_object(
      'pending', v_pending,
      'accepted', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'accepted'
      ),
      'duplicates', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'duplicate'
      ),
      'rejected', (
        select count(*)
        from public.release_candidates
        where run_id = p_run_id and status = 'rejected'
